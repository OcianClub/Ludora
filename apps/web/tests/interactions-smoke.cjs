const assert = require('node:assert/strict');
const path = require('node:path');
const fs = require('node:fs');
const { chromium } = require('playwright');
const base = process.env.LUDORA_WEB_TEST_URL || 'http://127.0.0.1:5188';
const output = path.resolve(__dirname, '../../../test-results/web-interactions');

(async () => {
  fs.mkdirSync(output, { recursive: true });
  const browser = await chromium.launch({ channel: 'msedge', headless: true });
  try {
    for (const width of [390, 1366]) for (const theme of ['dark','light']) {
      const context = await browser.newContext({ viewport: { width, height: 900 }, hasTouch: width === 390 });
      await context.addInitScript(theme => {
        localStorage.setItem('ludora_token','visual-test-only');
        localStorage.setItem('ludora_usuario',JSON.stringify({id:1,nome:'Alex Morgan',email:'visual@example.test'}));
        localStorage.setItem('ludora_clube',JSON.stringify({id:2,nome:'Ocian',meuPapel:'ADMIN'}));
        localStorage.setItem('ludora_clube_id','2');localStorage.setItem('ludora_tema',theme);
      },theme);
      const page=await context.newPage(), errors=[], requests=[];
      page.on('pageerror',e=>errors.push(e.message));
      page.on('request',r=>{if(r.url().includes('/jogadores?')) requests.push(r.url());});
      await page.route('**/*',r=>new URL(r.request().url()).origin===new URL(base).origin?r.continue():r.abort());
      await require('./visual-fixture.cjs').install(page);
      await page.goto(base+'/jogadores');
      const category=page.locator('.alunos-category').first();
      await category.waitFor();
      assert.equal(await page.locator('.alunos-students:visible').count(),0,'Todos os subs começam fechados');
      assert.equal(requests.filter(r=>r.includes('limite=')).length,0,'Nenhum atleta transferido antes de abrir');
      await category.locator('.alunos-category-toggle').click();
      await page.waitForFunction(()=>document.querySelector('.alunos-category .alunos-students')?.children.length===5);
      assert.ok(requests.some(r=>r.includes('limite=5')));
      await category.getByRole('button',{name:/Mostrar mais/}).click();
      await page.waitForFunction(()=>document.querySelector('.alunos-category .alunos-students')?.children.length===8);
      assert.ok(requests.some(r=>r.includes('offset=5')));
      assert.equal(await page.locator('.alunos-category').nth(1).locator('[aria-expanded=true]').count(),0);
      const gloves=category.locator('[data-position="Goleiro"]').first();
      await gloves.focus();
      await page.getByRole('tooltip').waitFor();
      assert.match(await page.getByRole('tooltip').innerText(),/Goleiro/);
      await page.keyboard.press('Escape');
      await page.getByRole('tooltip').waitFor({state:'hidden'});
      await page.screenshot({path:path.join(output,`players-${width}-${theme}.png`),fullPage:true});
      await category.locator('.alunos-category-toggle').click();
      await category.locator('.alunos-category-toggle').click();
      await page.waitForFunction(()=>document.querySelector('.alunos-category .alunos-students')?.children.length===5);
      assert.ok((await category.locator('.alunos-category-toggle').innerText()).includes('8 alunos · 1 sem camisa'));
      await category.getByRole('link',{name:'Abrir perfil de Adam Hayes'}).click();
      await page.getByRole('heading',{name:'Adam Hayes',exact:true}).waitFor();
      await page.screenshot({path:path.join(output,`profile-${width}-${theme}.png`),fullPage:true});
      await page.getByRole('link',{name:/Histórico completo/}).click();
      await page.getByRole('heading',{name:'Histórico de partidas'}).waitFor();
      await page.goBack();await page.getByRole('heading',{name:'Dados do jogador'}).waitFor();
      await page.getByRole('button',{name:'Editar jogador',exact:true}).click();
      const editor=page.getByRole('dialog',{name:'Editar jogador',exact:true});
      assert.equal(await editor.getByLabel('CPF · não editável').getAttribute('readonly'),'');
      await editor.getByLabel('Nome completo').fill('Adam Updated');
      await editor.getByRole('button',{name:'Salvar jogador'}).click();
      await page.getByRole('heading',{name:'Adam Updated',exact:true}).waitFor();
      await page.goBack();await category.waitFor();
      assert.equal(await category.locator('.alunos-category-toggle').getAttribute('aria-expanded'),'true');
      await page.goto(base+'/partidas');
      await page.getByRole('button',{name:'Nova partida',exact:true}).filter({visible:true}).click();
      const form=page.getByRole('dialog',{name:'Organizar partida',exact:true});
      await form.getByRole('button',{name:'Selecionar mandante',exact:true}).click();
      const categories=page.getByRole('dialog',{name:'Categoria da partida',exact:true});
      await categories.getByRole('button',{name:'SUB-7',exact:true}).click();
      const strip=categories.locator('.home-sub-strip');
      await page.waitForTimeout(400);
      const before=await strip.evaluate(el=>el.scrollLeft);
      const bounds=await strip.boundingBox();
      await page.mouse.move(bounds.x+bounds.width*.65,bounds.y+bounds.height/2);
      await page.mouse.down();
      await page.mouse.move(bounds.x+bounds.width*.65-115,bounds.y+bounds.height/2,{steps:12});
      const during=await strip.evaluate(el=>el.scrollLeft);
      assert.ok(during>before+40,'Drag movimenta a faixa antes de soltar');
      assert.equal(await strip.locator('[aria-pressed=true]').innerText(),'SUB-7','Seleção só muda no encaixe');
      await page.mouse.up();
      await page.waitForTimeout(600);
      assert.notEqual(await strip.locator('[aria-pressed=true]').innerText(),'SUB-7');
      await strip.hover();await page.mouse.wheel(0,110);await page.waitForTimeout(600);
      const center=await strip.evaluate(el=>{const b=el.querySelector('[aria-pressed=true]');return Math.abs(b.getBoundingClientRect().left+b.clientWidth/2-el.getBoundingClientRect().left-el.clientWidth/2);});
      assert.ok(center<4,`Snap central: diferença ${center}`);
      await categories.getByRole('button',{name:'SUB-7',exact:true}).click();
      await categories.getByRole('button',{name:'Usar categoria'}).click();
      await form.getByRole('button',{name:'Selecionar mandante',exact:true}).click();
      let picker=page.getByRole('dialog',{name:'Selecionar mandante',exact:true});
      assert.match(await picker.locator('.schedule-picker-options>button').first().innerText(),/Ocian/);
      await picker.getByRole('button',{name:/Santos/}).click();
      assert.match(await form.getByRole('status').innerText(),/Fora/);
      assert.ok(await form.getByRole('button',{name:'Selecionar visitante: Ocian'}).isVisible());
      await form.getByRole('button',{name:'Selecionar mandante: Santos'}).click();
      picker=page.getByRole('dialog',{name:'Selecionar mandante',exact:true});
      assert.equal(await picker.getByRole('button',{name:/Santos/}).getAttribute('aria-pressed'),'true');
      await picker.getByRole('button',{name:/Ocian/}).click();
      assert.ok(await form.getByRole('button',{name:'Selecionar visitante: Santos',exact:true}).isVisible(),'Inverter o mando preserva o adversário');
      assert.match(await form.getByRole('status').innerText(),/Em casa/);
      await form.getByRole('button',{name:'Data',exact:true}).click();
      const calendar=page.getByRole('dialog',{name:'Data da partida',exact:true});
      await calendar.screenshot({path:path.join(output,`calendar-${width}-${theme}.png`)});
      await calendar.locator('.match-calendar button:not(:disabled)').first().click();
      await form.getByLabel('Horário',{exact:true}).fill('1835');
      assert.equal(await form.getByLabel('Horário',{exact:true}).inputValue(),'18:35');
      await form.getByRole('combobox').fill('Ginásio');
      await form.getByRole('option').first().waitFor();
      await form.getByRole('combobox').press('ArrowDown');await form.getByRole('combobox').press('Enter');
      assert.equal(await form.getByRole('combobox').inputValue(),'Ginásio de demonstração');
      await form.screenshot({path:path.join(output,`create-${width}-${theme}.png`)});
      assert.ok(await form.evaluate(el=>el.scrollWidth<=el.clientWidth),'Sem overflow horizontal');
      await form.getByRole('button',{name:'Criar partida',exact:true}).click();
      const review=page.getByRole('dialog',{name:'Revisar partida',exact:true});await review.waitFor();
      assert.ok((await review.innerText()).includes('18:35'));
      let created=false;
      await page.route('**/partidas',r=>{if(r.request().method()!=='POST')return r.fallback();const body=r.request().postDataJSON();assert.equal(body.emCasa,true);assert.equal(body.horario,'18:35');created=true;return r.fulfill({status:201,json:{id:999,...body}});});
      await review.getByRole('button',{name:'Confirmar e criar'}).click();await review.waitFor({state:'hidden'});assert.ok(created);
      await page.goto(base+'/partidas/107');
      await page.getByRole('button',{name:'Editar partida',exact:true}).click();
      const gameEditor=page.getByRole('dialog',{name:'Editar partida',exact:true});
      await gameEditor.getByLabel('Horário',{exact:true}).fill('1945');
      await gameEditor.getByRole('button',{name:'Salvar alterações'}).click();await gameEditor.waitFor({state:'hidden'});
      assert.deepEqual(errors,[]);
      await context.close();console.log(`PASS ${width}px ${theme}: paginação, tooltip, drag, wheel, mando, data/hora, local, revisão`);
    }
  } finally {await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});

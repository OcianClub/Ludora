const { chromium, _electron } = require('playwright');
const fs = require('node:fs/promises');
const path = require('node:path');
const assert = require('node:assert/strict');

async function main() {
  const root = process.cwd(), local = path.join(root, '.local-demo/equipe');
  const out = path.join(root, 'test-results/usuarios');
  await fs.mkdir(out, { recursive: true });
  const contas = JSON.parse(await fs.readFile(path.join(local, 'contas.json'), 'utf8'));
  const clube = JSON.parse(await fs.readFile(path.join(local, 'clube-criado.json'), 'utf8'));
  const profile = await fs.mkdtemp(path.join(local, 'usuarios-profile-'));
  await fs.writeFile(path.join(profile, 'config.json'), JSON.stringify({ apiUrl: 'http://127.0.0.1:3018' }));
  const wrapper = path.join(profile, 'launch.cjs');
  await fs.writeFile(wrapper, `const { app } = require('electron'); app.setPath('userData', ${JSON.stringify(profile)}); require(${JSON.stringify(path.join(root, 'apps/desktop/out/main/index.js'))});`);
  const env = { ...process.env }; delete env.ELECTRON_RUN_AS_NODE; delete env.ELECTRON_RENDERER_URL;
  const app = await _electron.launch({ executablePath: require(path.join(root, 'apps/desktop/node_modules/electron')), args: [wrapper], env });
  const page = await app.firstWindow();
  page.setDefaultTimeout(12000);
  let browser;
  const admin = (method, endpoint, body) => page.evaluate(({ method, endpoint, body }) => window.ludora.api.requisicao(method, endpoint, body), { method, endpoint, body });
  const conta = contas.find(c => c.papel === 'SUPERADMIN');
  const cliente = contas.find(c => c.papel === 'USUARIO');
  const login = c => fetch('http://127.0.0.1:3018/auth/login', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(c) });
  async function escolher(root, campo, opcao) {
    await root.getByRole('combobox', { name: new RegExp(campo) }).click();
    await root.getByRole('option', { name: opcao, exact: true }).click();
  }
  try {
    const sessao = await (await login(cliente)).json(); assert.ok(sessao.token);
    await page.getByLabel('E-mail', { exact: true }).fill(conta.email);
    await page.getByLabel('Senha', { exact: true }).fill(conta.senha);
    await page.getByRole('button', { name: 'Entrar', exact: true }).click();
    await page.getByRole('link', { name: 'Usuários', exact: true }).click();
    await page.getByRole('button', { name: 'Mais filtros', exact: true }).click();
    const filtros = page.getByRole('region', { name: 'Filtrar usuários' });
    await filtros.getByRole('group', { name: 'Papel interno' }).getByText('Desenvolvedor', { exact: true }).click();
    await filtros.getByRole('button', { name: 'Aplicar filtros' }).click();
    await page.getByRole('button', { name: /Test DESENVOLVEDOR/ }).waitFor();
    assert.equal(await page.locator('.user-directory .ticket-card').count(), 1);
    await page.getByRole('button', { name: /Test DESENVOLVEDOR/ }).click();
    const contaDev = page.getByRole('dialog', { name: 'Gerenciar conta' });
    await contaDev.getByRole('button', { name: 'Vincular a um clube' }).click();
    const novoVinculo = page.getByRole('dialog', { name: 'Vincular a um clube' });
    await novoVinculo.getByRole('searchbox').fill(clube.nome);
    await novoVinculo.getByRole('group', { name: 'Clube Ludora' }).getByText(clube.nome, { exact: true }).click();
    await novoVinculo.getByRole('group', { name: 'Cargo no clube' }).getByText('Olheiro', { exact: true }).click();
    await novoVinculo.getByRole('button', { name: 'Salvar vínculo' }).click();
    await novoVinculo.waitFor({ state: 'hidden' });
    await contaDev.getByRole('button', { name: `Editar acesso em ${clube.nome}` }).click();
    const editarVinculo = page.getByRole('dialog', { name: `Editar acesso · ${clube.nome}` });
    assert.equal(await editarVinculo.getByRole('radio', { name: 'Olheiro' }).isChecked(), true);
    await editarVinculo.getByText('Visitante', { exact: true }).click();
    await editarVinculo.getByRole('button', { name: 'Salvar vínculo' }).click();
    await editarVinculo.waitFor({ state: 'hidden' });
    await contaDev.getByRole('button', { name: `Desvincular de ${clube.nome}` }).click();
    const desfazer = page.getByRole('dialog', { name: 'Desvincular do clube' });
    await desfazer.getByRole('checkbox').check();
    await desfazer.getByRole('button', { name: 'Confirmar alteração' }).click();
    await desfazer.waitFor({ state: 'hidden' });
    assert.equal(await contaDev.getByRole('button', { name: `Editar acesso em ${clube.nome}` }).count(), 0);
    await page.getByRole('button', { name: 'Encerrar sessões', exact: true }).click();
    const encerrar = page.getByRole('dialog', { name: 'Encerrar sessões', exact: true });
    await encerrar.getByText(/desenvolvedor@equipe.example.test/).waitFor();
    assert.equal(await encerrar.getByRole('button', { name: 'Confirmar alteração' }).isEnabled(), false);
    await encerrar.getByRole('button', { name: 'Voltar', exact: true }).click();
    await page.keyboard.press('Escape');
    await page.getByRole('dialog').waitFor({ state: 'hidden' });
    await page.screenshot({ path: path.join(out, 'filtro-escuro.png') });
    await page.getByRole('button', { name: 'Contas por clubes' }).click();
    await page.getByRole('searchbox', { name: 'Buscar clubes' }).fill(clube.nome);
    await page.getByRole('button', { name: new RegExp(clube.nome) }).click();
    await page.getByRole('button', { name: /Test USUARIO/ }).waitFor();
    await page.screenshot({ path: path.join(out, 'contas-por-clube.png') });
    assert.equal((await admin('PATCH', `/admin/clubes/${clube.id}/estado`, { ativo: true, motivo: 'Preparação da validação isolada.' })).status, 200);
    assert.equal((await admin('PATCH', `/admin/clubes/${clube.id}`, { escudo_arquivo: null })).status, 200);
    await page.getByRole('button', { name: 'Cadastro dos clubes' }).click();
    await escolher(page, '^Clube', clube.nome);
    await escolher(page, '^Dado pendente', 'Escudo do clube');
    await page.getByRole('button', { name: 'Test USUARIO', exact: true }).click();
    await page.getByRole('button', { name: 'Revisar aviso', exact: true }).click();
    const modal = page.getByRole('dialog', { name: 'Revisar aviso' });
    const mensagem = await modal.getByText(/^Complete o cadastro/).innerText();
    await page.screenshot({ path: path.join(out, 'previa-escuro.png') });
    const endpoint = `/admin/cadastro-pendente/${clube.id}`;
    const dev = (await admin('GET', '/admin/usuarios?interno=DESENVOLVEDOR')).data[0];
    assert.equal((await admin('POST', endpoint, { motivo: 'ESCUDO', destinatarios: [dev.id], mensagemEsperada: mensagem })).status, 403);
    await modal.getByRole('button', { name: 'Enviar aviso', exact: true }).click();
    await page.getByRole('status').getByText(/Aviso registrado em 1/).waitFor();
    assert.equal((await admin('POST', endpoint, { motivo: 'ESCUDO', destinatarios: [sessao.usuario.id], mensagemEsperada: mensagem })).status, 409);
    await page.getByRole('radio', { name: 'Tema claro', exact: true }).click();
    await page.getByRole('heading', { name: 'Escudo · Pendente' }).waitFor();
    await page.screenshot({ path: path.join(out, 'pendente-claro.png') });
    browser = await chromium.launch({ channel: 'msedge', headless: true });
    const web = await browser.newPage({ viewport: { width: 1200, height: 820 } });
    await web.addInitScript(({ s, c }) => {
      localStorage.setItem('ludora_token', s.token); localStorage.setItem('ludora_usuario', JSON.stringify(s.usuario));
      localStorage.setItem('ludora_clube_id', String(c.id)); localStorage.setItem('ludora_clube', JSON.stringify({ id: c.id, nome: c.nome, meuPapel: 'ADMIN' }));
    }, { s: sessao, c: clube });
    await web.goto('http://localhost:5198/dashboard');
    await web.getByRole('button', { name: /^Notificações, / }).filter({ visible: true }).click();
    await web.getByText('Cadastro do clube incompleto', { exact: true }).waitFor();
    await web.screenshot({ path: path.join(out, 'web-aviso.png') });
    await page.getByRole('button', { name: 'Dispensar tarefa', exact: true }).click();
    await page.getByLabel('Justificativa', { exact: true }).fill('Escudo será atualizado durante a próxima temporada.');
    await page.getByRole('button', { name: 'Confirmar dispensa' }).click();
    await page.getByRole('heading', { name: 'Escudo · Dispensada' }).waitFor();
    await page.getByRole('button', { name: 'Contas e acessos' }).click();
    await page.getByRole('searchbox', { name: 'Buscar usuários' }).fill(cliente.email);
    await page.getByRole('button', { name: /Test USUARIO/ }).click();
    const acesso = page.getByRole('dialog', { name: 'Gerenciar conta' });
    await acesso.getByRole('switch', { name: 'Situação da conta' }).click();
    await acesso.getByText('Adicionar motivo (opcional)', { exact: true }).click();
    await acesso.getByLabel('Motivo da alteração').fill('Teste isolado de bloqueio de sessão.');
    await acesso.getByRole('button', { name: 'Revisar acesso' }).click();
    const confirmar = page.getByRole('dialog', { name: 'Suspender conta' });
    await confirmar.getByText(cliente.email, { exact: true }).waitFor();
    assert.equal(await confirmar.getByRole('button', { name: 'Confirmar alteração' }).isEnabled(), false);
    assert.equal((await login(cliente)).status, 200);
    await confirmar.getByLabel('Confirmo a ação para esta conta.').check();
    await page.screenshot({ path: path.join(out, 'confirmar-suspensao.png') });
    await confirmar.getByRole('button', { name: 'Confirmar alteração' }).click();
    await confirmar.waitFor({ state: 'hidden' });
    assert.equal((await login(cliente)).status, 403);
    assert.equal((await fetch('http://127.0.0.1:3018/usuarios/me', { headers: { Authorization: `Bearer ${sessao.token}` } })).status, 401);
    assert.equal((await admin('PATCH', `/admin/usuarios/${sessao.usuario.id}/controle`, { cargo: 'USUARIO', suspenso: false, motivo: 'Encerramento da validação isolada.' })).status, 200);
    console.log('PASS filtro e suspensão no Electron, token revogado, aviso restrito, deduplicação, notificação real no web e dispensa.');
  } catch (e) { await page.screenshot({ path: path.join(out, 'falha.png') }); throw e; }
  finally { await browser?.close(); await app.close(); }
}
main().catch(e => { console.error(e.message); process.exitCode = 1; });

function cnpjTeste() {
  const base = String(randomInt(10000000, 99999999)) + '0001';
  function d(v) { const soma = [...v].reduce((n, c, i) => n + Number(c) * (2 + (v.length - i - 1) % 8), 0); return (11 - soma % 11) % 11 % 10; }
  return base + d(base) + d(base + d(base));
}
